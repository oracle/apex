  CREATE OR REPLACE FORCE EDITIONABLE VIEW "FSP_EMPLOYEE_EVENTS_V" ("EVENT_ID", "EVENT_TITLE", "EVENT_START", "EVENT_END", "EVENT_TYPE", "EVENT_STATUS", "EVENT_SCOPE", "DELIVERY_MODE", "DESCRIPTION", "EMPLOYEE_ID", "FIRST_NAME", "LAST_NAME", "GEOGRAPHIC_REGION", "COST_CENTER", "EMPLOYEE_NAME", "EVENT_DISPLAY", "START_MONTH", "DURATION_HOURS", "EVENT_SUMMARY","LOCATION_ID") AS 
  SELECT ev.event_id,
       ev.event_title,
       ev.calendar_start AS event_start,
       ev.calendar_end AS event_end,
       ev.event_type,
       ev.event_status,
       ev.event_scope,
       ev.delivery_mode,
       ev.description,
       e.employee_id,
       e.first_name,
       e.last_name,
       e.geographic_region,
       cc.cost_center_description AS cost_center,
       e.first_name || ' ' || e.last_name AS employee_name,
       TO_CHAR(ev.calendar_start, 'HH12:MI AM') || ' - ' || TO_CHAR(ev.calendar_end, 'HH12:MI AM') || CHR(10) || REGEXP_REPLACE(ev.event_title, ' — .*$', '') || CHR(10) || e.first_name || ' ' || e.last_name AS event_display,
       TO_CHAR(ev.calendar_start, 'FMMonth YYYY', 'NLS_DATE_LANGUAGE=English') AS start_month,
       ev.duration_hours,
       INITCAP(REPLACE(ev.delivery_mode, '_', ' ')) || ' · ' || TO_CHAR(ev.duration_hours, 'FM990D0') || 'h · ' || INITCAP(LOWER(ev.event_status)) AS event_summary,
       ev.location_id
  FROM (
       SELECT s.*,
              s.event_start + NUMTODSINTERVAL(TRUNC(SYSDATE) - DATE '2026-07-01', 'DAY') AS calendar_start,
              s.event_end + NUMTODSINTERVAL(TRUNC(SYSDATE) - DATE '2026-07-01', 'DAY') AS calendar_end,
              ROUND((CAST(s.event_end AS DATE) - CAST(s.event_start AS DATE)) * 24, 2) AS duration_hours
         FROM fsp_employee_events s
       ) ev
  JOIN fsp_employees e
    ON e.employee_id = ev.employee_id
  LEFT JOIN fsp_cost_centers cc
    ON cc.cost_center_id = e.cost_center_id;

